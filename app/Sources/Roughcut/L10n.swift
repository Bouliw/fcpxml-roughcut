/// "4 min", "45 s".
func shortDuration(_ seconds: Double) -> String {
    let s = Int(seconds.rounded())
    return s >= 60 ? L10n.t("min", Int((Double(s) / 60).rounded())) : L10n.t("sec", s)
}

/// "8:12".
func clock(_ seconds: Double) -> String {
    let s = Int(seconds.rounded())
    return String(format: "%d:%02d", s / 60, s % 60)
}
